/** Ship the nav package's dependency-free flow baker with the standalone studio. */
import { readFileSync, writeFileSync } from 'node:fs';
const source=new URL('../packages/nav/src/Flow.ts',import.meta.url),target=new URL('../packages/studio/rules/nav/Flow.ts',import.meta.url);
const text='// Generated by scripts/studio-nav.mjs from packages/nav/src/Flow.ts.\n'+readFileSync(source,'utf8');
if(process.argv.includes('--check')){if(readFileSync(target,'utf8')!==text)throw new Error('Run node scripts/studio-nav.mjs');}
else writeFileSync(target,text);
