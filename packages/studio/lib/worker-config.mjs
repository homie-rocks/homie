const parse=t=>JSON.parse(t.replace(/^\s*\/\/.*$/gm,''));
const read=file=>existsSync(file)?parse(readFileSync(file,'utf8')):{};
function merge(base,custom) {
  if(Array.isArray(custom))return custom;
  if(custom && typeof custom==='object')return Object.fromEntries([...new Set([...Object.keys(base??{}),...Object.keys(custom)])].sort().map(k=>[k,k in custom?merge(base?.[k],custom[k]):base[k]]));
  return custom;
}
/** Regenerate from declarations/custom config; migrate only newly encountered manual crons. */
export function updateWorkerConfig(root,generated) {
  const file=configPath(root),base=parse(generated),custom=read(join(root,'wrangler.custom.json'));
  // Preserve studio cron edits made before/after generation, including old wrangler files.
  // Compare against the previous output to discover manual additions. Custom entries
  // retain ownership even when their text equals a generated tick.
  const previous=read(file);
  let previousCrons=[];
  try {previousCrons=JSON.parse(previous.vars?.STUDIO_FUNCTION_CRONS??'[]');}catch {}
  const extra=(previous.triggers?.crons??[]).filter(c=>!previousCrons.includes(c)&&!(custom.triggers?.crons??[]).includes(c));
  if(extra.length) {
    custom.triggers={...custom.triggers,crons:[...new Set([...(custom.triggers?.crons??[]),...extra])].sort()};
    writeFileSync(join(root,'wrangler.custom.json'),JSON.stringify(custom,null,2)+'\n');
  }
  const next=merge(base,custom);
  next.vars={...next.vars,HOMIE_CONCEPT:readStudio(root).concept===true?'1':'0'};
  verifiedMcpConfig(root);
  if(publicMcpSetup(root)) {
    next.vars={...next.vars,STRIPE_CHECKOUT_MODE:'links',STRIPE_SHOP_LINKS_ASSET:'/_site/stripe-shop-links.json'};
    delete next.vars.STRIPE_SHOP_LINKS;
  }
  // Crons are additive: studio-owned entries cannot erase required toolkit ticks.
  const crons=[...new Set([...(base.triggers?.crons??[]),...(custom.triggers?.crons??[])])].sort();
  next.triggers={...next.triggers,crons}; // [] explicitly removes old generated triggers in Wrangler.
  next.vars={...next.vars,STUDIO_FUNCTION_CRONS:JSON.stringify(crons),STUDIO_FUNCTION_MANAGED_CRONS:JSON.stringify(base.triggers?.crons??[])};
  const text='// Generated by homie-studio. Edit studio.json or wrangler.custom.json, then build.\n'+JSON.stringify(next,null,2)+'\n';
  if(!existsSync(file)||readFileSync(file,'utf8')!==text) {const temp=`${file}.${process.pid}.tmp`;writeFileSync(temp,text);renameSync(temp,file);}
}
export function refreshWorkerConfig(root,overrides={}) {
  const studio=readStudio(root),cf=studio.cloudflare;
  if(!cf?.worker)return;
  const metadata=read(join(root,'site/src/functions/declarations.json'));
  const functions=Array.isArray(metadata)?metadata:[];
  const tools=read(join(root,'site/src/tools/declarations.json'));
  const ai=cf.ai??listExperiences(root).some(g=>g.decide===true || g.chat!==false && (g.chat?.mode??'text')==='text' && g.chat?.ai!==false);
  const paid=paidReleases(root).length>0||existsSync(join(root,'shop.json'))||tools.paid===true;
  updateWorkerConfig(root,wranglerConfig({workerRoutes:staticWorkerRoutes(read(join(root,'site/dist/games.json'))),worker:cf.worker,name:studio.name,d1:cf.d1,d1Id:cf.d1Id,r2:cf.r2,layout:layoutOf(root),ai,paidParts:paid,partsRateLimit:cf.purchaseRateLimit??null,routes:cf.routes??null,eventFeeds:studio.mcp?.events,triggers:{crons:[scheduleTrigger(functions,{eventFeeds:Object.keys(studio.mcp?.events??{}).length>0})].filter(Boolean)},...overrides}));
}
