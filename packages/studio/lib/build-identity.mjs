/** Content identity of the runtime, independent of a studio's package pin or git commit. */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
export function runtimeIdentity() {
  const hash = createHash('sha256');
  function walk(dir) {
    for (const entry of readdirSync(join(root, dir), {
      withFileTypes: true
    }).sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))) {
      const path = dir + '/' + entry.name;
      if (entry.isDirectory()) walk(path);
      else if (/\.(mjs|ts|json)$/.test(path) && path !== 'worker/build-id.mjs')
        hash
          .update(path + '\0')
          .update(readFileSync(join(root, path)))
          .update('\0');
    }
  }
  for (const dir of ['worker', 'rules', 'netplay']) walk(dir);
  return {
    version: JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
      .version,
    sha256: hash.digest('hex')
  };
}
export function stampRuntime(check = false) {
  const text =
      '// Generated by lib/build-identity.mjs; identifies the bundled runtime sources.\nexport const STUDIO_BUILD = Object.freeze(' +
      JSON.stringify(runtimeIdentity()) +
      ');\n',
    path = join(root, 'worker/build-id.mjs');
  if (check) {
    if (readFileSync(path, 'utf8') !== text)
      throw Error(
        'Runtime identity is stale: node packages/studio/lib/build-identity.mjs --write'
      );
  } else writeFileSync(path, text);
}
if (process.argv[1] === fileURLToPath(import.meta.url))
  stampRuntime(process.argv.includes('--check'));
